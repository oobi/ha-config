"""Convert the Blender colour IDs into alpha masks and browser configuration."""
import json
from pathlib import Path
import numpy as np
from PIL import Image

HERE=Path(__file__).resolve().parent
data=json.loads((HERE/'room-interaction.json').read_text())
pixels=np.asarray(Image.open(HERE/'room-id.png').convert('RGB')).astype(np.float32)
peak=pixels.max(axis=2)
direction=pixels/np.maximum(peak[:,:,None],1)*255
best=np.full(peak.shape,1e10); labels=np.full(peak.shape,-1,dtype=np.int8)
for i,room in enumerate(data['rooms']):
    color=np.array([int(room['mask_color'][j:j+2],16) for j in (1,3,5)])
    distance=np.sum((direction-color)**2,axis=2)
    take=distance<best; labels[take]=i; best[take]=distance[take]
(HERE/'masks').mkdir(exist_ok=True)
for i,room in enumerate(data['rooms']):
    alpha=np.where((labels==i)&(peak>12)&(best<16000),peak,0).astype(np.uint8)
    assert np.count_nonzero(alpha)>100,room['id']
    out=np.full((*alpha.shape,4),255,dtype=np.uint8); out[:,:,3]=alpha
    Image.fromarray(out).save(HERE/room['mask'],optimize=True)
    del room['mask_color']
(HERE/'room-config.js').write_text('// Generated by prepare-interaction.py. Entity IDs come from existing room YAML.\n'
    +'globalThis.FloorplanRoomConfig = '+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n')
print('Prepared',len(data['rooms']),'visible-floor masks and room-config.js')
